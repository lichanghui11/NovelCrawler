# src package
# 这是包的初始化文件，不是入口文件
# 这个文件的作用是把当前文件所在的这个 src 文件夹注册为一个 Python 包,
# 从而可以在其他文件中通过 import src.模块名.类名 的方式导入 src 文件夹中的模块。
# 实际在 py3 里面不强制，但仍然建议这样做

# 1. 该文件可以是空文件，只标记为包
# 2. 该文件也可以包含 包级别 的初始化代码，类似于 前端项目里面在 main.js 文件里面的初始化操作
# 3. 在 Python 里面，不用显示导出，每个文件的名称就是一个模块的名字，通过 . 的访问方式就可以访问到一个文件里面定义的函数或类（这里指的是模块的名字，不是包的名字）

# ❌ 每个文件是"模块"，不是"包"
# 包 = 目录 + __init__.py
# 模块 = 单个 .py 文件

# ❌ 错误写法
# import src.模块名.类名  # 这样不行

# ✅ 正确写法
# from src.模块名 import 类名  # 推荐

# 或
# import src.模块名  # 推荐

# 4. Python 的入口文件是随意命名的，任何文件都可以被执行
